from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from datetime import datetime

# --- Device Schemas ---
class DeviceCreate(BaseModel):
    device_id: str = Field(..., description="Unique Device Identifier (e.g., MED-001)")
    device_name: str = Field(..., description="Device Name (e.g., Patient Monitor 01)")
    device_type: str = Field("PATIENT_MONITOR", description="PATIENT_MONITOR, ECG_MONITOR, etc.")
    public_key: str = Field(..., description="Hex or base64-encoded ML-DSA-65 public key")

class DeviceResponse(BaseModel):
    id: int
    device_id: str
    device_name: str
    device_type: str
    public_key: str
    trust_status: str
    connection_status: str
    registered_at: datetime
    last_seen: datetime
    revoked_at: Optional[datetime] = None

    class Config:
        from_attributes = True

class DeviceRevoke(BaseModel):
    reason: str = Field("Administrative revocation", description="Reason for device revocation")

# --- Cryptographic Handshake Schemas ---
class HandshakeInitRequest(BaseModel):
    device_id: str
    client_random: str = Field(..., description="Fresh random nonce generated by device (hex)")

class HandshakeChallengeResponse(BaseModel):
    gateway_id: str
    device_id: str
    challenge: str = Field(..., description="Fresh random challenge bytes (hex) to be signed by device")
    gateway_kem_public_key: str = Field(..., description="Gateway ephemeral ML-KEM-768 public key (hex)")
    timestamp: str

class HandshakeCompleteRequest(BaseModel):
    device_id: str
    challenge: str = Field(..., description="The challenge that was signed")
    client_signature: str = Field(..., description="ML-DSA-65 signature over challenge (hex)")
    kem_ciphertext: str = Field(..., description="ML-KEM-768 ciphertext produced by device encapsulating to gateway KEM key (hex)")

class HandshakeResponse(BaseModel):
    session_id: str
    gateway_id: str
    device_id: str
    status: str
    expires_at: str
    message: str

# --- Secure Communication Schemas ---
class EncryptedMessagePayload(BaseModel):
    device_id: str
    session_id: str
    sequence_number: int
    nonce: str = Field(..., description="12-byte AES-GCM nonce (hex)")
    ciphertext: str = Field(..., description="Encrypted payload bytes (hex)")
    authentication_tag: str = Field(..., description="16-byte AES-GCM tag (hex)")

class MessageVerificationResponse(BaseModel):
    status: str
    result: str
    message: str
    sequence_number: int
    device_id: str
    timestamp: str

# --- Telemetry Schemas ---
class TelemetryReadings(BaseModel):
    heart_rate: Optional[float] = None
    spo2: Optional[float] = None
    temperature: Optional[float] = None
    respiratory_rate: Optional[float] = None

class TelemetryPayload(BaseModel):
    device_id: str
    timestamp: str
    readings: TelemetryReadings
    data_source: str = "SYNTHETIC"

class TelemetryRecordResponse(BaseModel):
    id: int
    device_id: str
    timestamp: datetime
    heart_rate: Optional[float]
    spo2: Optional[float]
    temperature: Optional[float]
    respiratory_rate: Optional[float]
    data_source: str

    class Config:
        from_attributes = True

# --- Firmware Verification Schemas ---
class FirmwareManifest(BaseModel):
    firmware_id: str
    device_model: str
    firmware_version: str
    security_version: int
    sha256: str
    signing_key_id: str
    release_timestamp: str

class FirmwareVerificationResponse(BaseModel):
    firmware_id: str
    device_model: str
    firmware_version: str
    security_version: int
    file_hash: str
    signing_key_id: str
    signature_status: str
    integrity_status: str
    compatibility_status: str
    anti_rollback_status: str
    verification_result: str
    reason: str
    created_at: datetime

    class Config:
        from_attributes = True

# --- Attack Simulator Schemas ---
class AttackSimulationRequest(BaseModel):
    target_device: str
    attack_type: str = Field(..., description="DEVICE_IMPERSONATION, MESSAGE_TAMPERING, REPLAY_ATTACK, UNAUTHORIZED_COMMAND, FIRMWARE_TAMPERING, REQUEST_FLOODING")
    custom_params: Optional[Dict[str, Any]] = None

class AttackSimulationResponse(BaseModel):
    event_id: str
    attack_type: str
    target_device: str
    severity: str
    result: str
    reason: str
    timestamp: str
    detection_module: str
    technical_details: Dict[str, Any]

# --- Security Events & Audit Schemas ---
class SecurityEventResponse(BaseModel):
    id: int
    event_id: str
    event_type: str
    attack_type: str
    device_id: Optional[str]
    severity: str
    result: str
    reason: str
    timestamp: datetime
    detection_module: str

    class Config:
        from_attributes = True

class SecurityStatsResponse(BaseModel):
    total_devices: int
    online_devices: int
    offline_devices: int
    suspicious_devices: int
    revoked_devices: int
    total_attacks_simulated: int
    attacks_blocked: int
    active_sessions: int
    failed_auth_attempts: int
    firmware_failures: int
    recent_events: List[SecurityEventResponse]

class AuditLogResponse(BaseModel):
    id: int
    event_type: str
    actor: str
    event_data: str
    previous_hash: str
    current_hash: str
    timestamp: datetime

    class Config:
        from_attributes = True

class AuditChainVerificationResponse(BaseModel):
    valid: bool
    total_records: int
    tampered_index: Optional[int] = None
    message: str

# --- Auth Schemas ---
class UserLoginRequest(BaseModel):
    username: str
    password: str

class TokenResponse(BaseModel):
    access_token: str
    token_type: str = "bearer"
    role: str
    username: str

class UserResponse(BaseModel):
    id: int
    username: str
    role: str
    email: Optional[str] = None
    full_name: Optional[str] = None
    hospital_name: Optional[str] = "St. Jude Memorial Hospital"
    last_login: Optional[datetime] = None
    password_updated_at: Optional[datetime] = None
    active_sessions: Optional[int] = 1
    created_at: datetime

    class Config:
        from_attributes = True

class ChangePasswordRequest(BaseModel):
    current_password: str
    new_password: str

class ForgotPasswordRequest(BaseModel):
    identifier: str

class ResetPasswordRequest(BaseModel):
    token: str
    new_password: str

class GenericMessageResponse(BaseModel):
    status: str = "SUCCESS"
    message: str
    reset_token: Optional[str] = None

# --- Cryptography & Benchmark Schemas ---
class CryptoStatusResponse(BaseModel):
    ml_kem_768_available: bool
    ml_dsa_65_available: bool
    aes_256_gcm_available: bool
    hkdf_sha256_available: bool
    argon2id_available: bool
    active_sessions_count: int
    successful_handshakes_count: int
    failed_signature_verifications: int
    failed_message_authentications: int
    replay_attacks_detected: int

class BenchmarkMetric(BaseModel):
    operation: str
    algorithm: str
    avg_latency_ms: float
    min_latency_ms: float
    max_latency_ms: float
    iterations: int
    key_or_payload_bytes: int

class CryptoBenchmarkResponse(BaseModel):
    metrics: List[BenchmarkMetric]
    system_info: Dict[str, str]
    timestamp: str
